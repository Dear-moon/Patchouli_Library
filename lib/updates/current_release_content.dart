- 小说、封面和插图归各自权利人所有。请合法使用内容、遵守来源网站规则，不绕过访问限制、不破解 DRM，不传播或出售未经授权的内容。
- 第三方服务可能调整或暂时不可用。升级、同步或整理存储前，建议备份重要阅读记录；反馈问题时请勿发送密码、Cookie 或令牌。

### 本地导入与书库整理

- **修复部分 EPUB 无法导入、提示“操作未完成”的问题**，改善复杂样式、特殊文件名和图片资源的兼容性。
- 缺失或不支持的资源会给出更明确的提示，保留插图前后的正文，避免静默遗漏内容。
- 改善 EPUB 注释弹窗、日文注音、段落对齐、分隔线及混合横竖排的显示。
- 批量整理新增「修复与整理」，支持升级旧 EPUB 排版、重建原书封面及整理可恢复的重复资源，保留原书、目录、进度、书签和分类。
- 支持自定义本地封面、恢复原书封面，以及多选书籍后统一移动分类。
- 优化大批量导入的临时空间占用，一本失败不影响其他书籍。

### 阅读体验与个性化

- **阅读字号最低支持 10 pt**，支持逐号调整，默认字号不变。
- 支持导入阅读背景图片，调整显示方式与背景浓度；可仅应用于当前书籍。
- 新增单书独立排版，可分别保存字体、字号、行距、边距、配色和阅读方式；增加字重、字间距调整。
- 「纸页翻动」升级为跟随手指弯曲的纸面，支持纸背、柔和阴影和拖回取消；大屏对页从书缝翻动，竖排保持左右翻页。
- 目录面板左侧为「章节进度」、右侧为「章节目录」，优先打开进度调整。
- 新增整书进度和整书查找。查找默认使用本地及缓存内容，读取未缓存章节前会征求确认。
- 改善控件收放时的黑白闪烁、章节标题突然消失及向下阅读时百分比倒退的问题。

### 主题配色与字体

- 新增主题配色：保留原色、跟随系统莫奈配色，或自行选择主色；支持从图片自动推荐颜色及手动取色。
- 新增「图标莫奈取色」开关，支持的 Android 桌面可使用主题图标。
- 提供思源宋体、思源黑体、霞鹜文楷屏幕版、朱雀仿宋和芫荽五款可下载字体，**不再随安装包预装字库**。
- 下载后的字体可离线使用、删除或重新下载；继续支持导入自己的字体，App 与阅读器可分别设置。
- 字体下载、书籍缓存和应用更新统一使用原位细圆环进度，支持直接停止，不再额外占用大块区域。

### 听书与跨设备续读

- 新增系统朗读引擎选择，可识别设备已安装的引擎及音色；是否支持离线朗读取决于所选引擎。
- 保留 **0.5～3 倍速**、段落跟随、睡眠定时和续听。
- **仅在「阅读设置 → 听书」中点击播放或继续播放时**，显示约四秒后自动消失的操作提示：

  > 双击其他段落可快速跳转朗读；双击当前段落可暂停，再次双击继续播放。

- 「局域网续读」移至设置首页，支持同一 Wi-Fi 自动发现设备、首次确认配对及之后自动重连。
- 本地书的「目录 → 章节进度」新增 **「在其他设备上续读」**。对方缺书时传送选定书籍，已有同书时只同步位置，不重复复制。
- 已配对设备支持书签、摘录分类和书籍分类的自动增量同步，并可处理同步冲突；同步时两端 App 需保持前台。
- 修复接收方已在阅读器内时，「继续阅读」无法生效的问题。

### 加载、缓存与界面

- 修复整书缓存遗漏插图的问题，正文图片和独立插图章节一并保存；失败时保留已有内容，支持继续缓存。
- 刷新时保留已有书目、位置和内容，骨架屏仅用于首次加载，不再反复覆盖立体书架。
- 改善发现、搜索、分类、详情和正文加载失败后的自动恢复；临时连接异常时尝试可用备用线路。
- 优化账号状态保存和恢复，临时网络异常不再直接清除有效登录。
- 发现页左上角以 App 图标替代 W8，保持原有大小和标题对齐。
- **修复「关于 → 项目介绍与下载」点击无反应的问题。**
- 更新弹窗、关于页及详细更新说明支持 Markdown，重点、列表和链接更清楚。

### 故障排查与性能

- 「我的」页在「关于」下方新增 **「故障排查与联系开发者」**。
- 支持一键复制版本、设备信息、错误原因和定位信息，方便私信开发者或提交 Issue。
- **只记录错误，不记录正常使用过程，不自动上传**；支持合并重复错误及清空记录。
- 减少长章节分页、竖排重排、大书库恢复和分类筛选时的额外开销。
- 继续精简包体与启动准备工作，保留现有玻璃效果、阅读动效和功能。
''';
